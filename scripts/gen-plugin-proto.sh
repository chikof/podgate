#!/usr/bin/env bash
# Regenerate src/middleware/plugin/gen.rs from proto/podgate_plugin.proto.
#
# The generated Rust is committed, so a build needs neither `protoc` nor a build script. This
# script needs no `protoc` either: it compiles the .proto with `protox` (a protobuf compiler
# written in Rust) and generates the messages with `prost-build`, in a scratch crate outside the
# workspace. It needs network access to fetch those two crates.
#
# Usage: scripts/gen-plugin-proto.sh          rewrite gen.rs
#        scripts/gen-plugin-proto.sh --check  fail when gen.rs is not what the .proto generates
# CARGO overrides the cargo to call.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
proto=$root/proto/podgate_plugin.proto
out=$root/src/middleware/plugin/gen.rs
cargo=${CARGO:-cargo}
mode="write"
[ "${1:-}" = "--check" ] && mode="check"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/src" "$work/out"

cat >"$work/Cargo.toml" <<TOML
[package]
name = "gen-plugin-proto"
version = "0.0.0"
edition = "2024"
publish = false

[dependencies]
prost-build = "=0.14.6"
protox = "=0.10.0"

[workspace]
TOML

cat >"$work/src/main.rs" <<'RS'
fn main() {
    let mut args = std::env::args().skip(1);
    let (Some(proto), Some(include), Some(out)) = (args.next(), args.next(), args.next()) else {
        eprintln!("usage: gen-plugin-proto <proto> <include dir> <out dir>");
        std::process::exit(2);
    };
    let descriptors = protox::compile([proto], [include]).expect("the .proto compiles");
    prost_build::Config::new()
        .out_dir(out)
        .compile_fds(descriptors)
        .expect("prost generates the messages");
}
RS

(cd "$work" && "$cargo" run --quiet -- "$proto" "$root/proto" "$work/out")

{
  echo '// @generated by scripts/gen-plugin-proto.sh from proto/podgate_plugin.proto. Do not edit.'
  cat "$work/out/podgate.plugin.v1.rs"
} >"$work/gen.rs"

if [ "$mode" = check ]; then
  cmp -s "$work/gen.rs" "$out" || { echo "gen.rs is stale: run scripts/gen-plugin-proto.sh" >&2; exit 1; }
else
  mkdir -p "$(dirname "$out")"
  cp "$work/gen.rs" "$out"
fi
