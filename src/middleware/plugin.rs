/// A phase of a request a middleware asks its plugin about.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "snake_case")]
enum PhaseName {
    /// The request head.
    RequestHeaders,
    /// The request head and the buffered body.
    RequestBody,
    /// The upstream's response head.
    ResponseHeaders,
}

/// What a failed call means for the request.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Deserialize, schemars::JsonSchema)]
#[serde(rename_all = "snake_case")]
enum OnPluginError {
    /// The request is answered `503`.
    #[default]
    FailClosed,
    /// The request goes on without the plugin.
    FailOpen,
}

/// Whether the request body is sent, and how much of it may be.
#[derive(Debug, Clone, Copy, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub(super) struct BodyConfig {
    /// The largest body that is buffered and sent; a larger one is refused with `413`.
    max_bytes: usize,
}

/// The configuration of a `plugin` middleware.
#[derive(Debug, Deserialize, schemars::JsonSchema)]
#[serde(deny_unknown_fields)]
pub(super) struct Config {
    /// The plugin's name in the operator's `PLUGINS_FILE`.
    plugin: String,
    /// Passed to the plugin as it is; at most 16 KiB of JSON. The plugin must treat it as
    /// untrusted input.
    #[serde(default)]
    config: Option<Value>,
    /// The phases to ask the plugin at: `request_headers` (the default), `request_body`,
    /// `response_headers`.
    #[serde(default)]
    phases: Option<Vec<PhaseName>>,
    /// `fail_closed` (the default) or `fail_open`.
    #[serde(default)]
    on_plugin_error: Option<OnPluginError>,
    /// The deadline of one call, in milliseconds: `plugin` 1 to 1000 (default 50), `llm_guard`
    /// 1 to 10000 (default 2000), and never more than `REQUEST_TIMEOUT_SECS`.
    #[serde(default)]
    timeout_ms: Option<u32>,
    /// The request headers to send. Without it all but `authorization`, `proxy-authorization`
    /// and `cookie`; with it exactly these.
    #[serde(default)]
    request_headers: Option<Vec<String>>,
    /// The response headers to send at `response_headers`. Without it all but `set-cookie`.
    #[serde(default)]
    response_headers: Option<Vec<String>>,
    /// Required by, and only with, the `request_body` phase.
    #[serde(default)]
    body: Option<BodyConfig>,
}

/// The phases a middleware asks.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
struct Phases {
    request_headers: bool,
    request_body: bool,
    response: bool,
}

impl Phases {
    fn has(self, phase: Phase) -> bool {
        match phase {
            Phase::RequestHeaders => self.request_headers,
            Phase::RequestBody => self.request_body,
            Phase::ResponseHeaders => self.response,
            Phase::Unspecified => false,
        }
    }

    fn names(self) -> Vec<&'static str> {
        let mut out = Vec::new();
        if self.request_headers {
            out.push("request_headers");
        }
        if self.request_body {
            out.push("request_body");
        }
        if self.response {
            out.push("response_headers");
        }
        out
    }

    fn within(self, other: Self) -> bool {
        (!self.request_headers || other.request_headers)
            && (!self.request_body || other.request_body)
            && (!self.response || other.response)
    }
}

