//! The `plugin` middleware: asks a plugin, a separate process the operator declared, what to do
//! with a request. Full reference: `docs/ref/mw-plugin.md`.
//!
//! ```json
//! { "name": "sso", "type": "plugin", "plugin": "headeradder",
//!   "config": {"header": "x-hello"}, "phases": ["request_headers", "response_headers"],
//!   "on_plugin_error": "fail_closed", "timeout_ms": 50 }
//! ```
//!
//! No plugin code runs in podgate. A plugin is declared in `PLUGINS_FILE` (process
//! configuration, never a snapshot) with the tenants that may use it; a snapshot can only name
//! one that lists the app's tenant (`unknown_plugin`, `plugin_forbidden`). Each call is one unary
//! gRPC request over the plugin's unix socket (`proto/podgate_plugin.proto`, [`wire`]) with a
//! deadline, a size cap, a place among the plugin's calls in flight and a charge to the tenant's
//! buffer budget; a plugin that keeps failing is not called for a while (its circuit).
//!
//! What the plugin sees: the request line, the headers named by `request_headers` (all but
//! `authorization`, `proxy-authorization` and `cookie` when it is not set), the app, tenant and
//! router, the client address and the middleware's opaque `config`. Bodies only with `body`.
//! What it can do: continue, replace or remove request headers, add response headers, or answer
//! the request. Headers that frame the message or belong to the connection are refused.
//!
//! `on_plugin_error` decides what a failed call means: `fail_closed` (the default) answers
//! `503 {"error":"plugin unavailable"}`, `fail_open` lets the request go on without the plugin.
//! A tenant over its buffer budget gets `503` either way.

