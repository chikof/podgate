fn invalid(message: impl std::fmt::Display) -> Invalid {
    Invalid::new("invalid_middleware", format!("plugin: {message}"))
}

/// Parses a list of header names: valid, no repeats.
fn names(list: &[String], field: &str) -> Result<Box<[HeaderName]>, Invalid> {
    if list.len() > MAX_NAMES {
        return Err(invalid(format!(
            "`{field}` lists more than {MAX_NAMES} names"
        )));
    }
    let mut out: Vec<HeaderName> = Vec::with_capacity(list.len());
    for raw in list {
        let name = HeaderName::from_bytes(raw.as_bytes())
            .map_err(|_| invalid(format!("`{field}`: {raw:?} is not a header name")))?;
        if !out.contains(&name) {
            out.push(name);
        }
    }
    Ok(out.into_boxed_slice())
}

/// A header a plugin may set or remove: valid, and not one that frames the message or belongs
/// to the connection (`host`, `content-length`, `connection`, `proxy-*`, ...).
fn editable(name: &str) -> Result<HeaderName, String> {
    let parsed = HeaderName::from_bytes(name.as_bytes())
        .map_err(|_| format!("{name:?} is not a header name"))?;
    if headers::FORBIDDEN.contains(&parsed.as_str()) || parsed.as_str().starts_with("proxy-") {
        return Err(format!(
            "{parsed} frames the message or belongs to the connection"
        ));
    }
    Ok(parsed)
}

fn pair(header: &Header) -> Result<(HeaderName, HeaderValue), String> {
    let name = editable(&header.name)?;
    let value = HeaderValue::from_bytes(&header.value)
        .map_err(|_| format!("the value of {name} is not a valid header value"))?;
    Ok((name, value))
}

/// A plugin's answer to a request, checked.
#[derive(Debug, Default)]
struct Applied {
    remove: Vec<HeaderName>,
    set: Vec<(HeaderName, HeaderValue)>,
    add_response: Vec<(HeaderName, HeaderValue)>,
    respond: Option<Reply>,
    /// The charge for the answer, kept while the request still holds some of it.
    charge: Option<BufferGuard>,
}

/// A response the plugin wrote.
#[derive(Debug)]
struct Reply {
    status: u16,
    headers: Vec<(HeaderName, HeaderValue)>,
    body: Bytes,
}

/// Checks `decision` for `phase`: what podgate can apply, and nothing it cannot.
fn validate(decision: Decision, phase: Phase) -> Result<Applied, String> {
    let request_phase = matches!(phase, Phase::RequestHeaders | Phase::RequestBody);
    let action = Action::try_from(decision.action)
        .map_err(|_| format!("the action {} is not known", decision.action))?;
    let mut applied = Applied::default();
    match action {
        Action::Respond => {
            if !request_phase {
                return Err("a response phase cannot answer the request".to_owned());
            }
            if !decision.set_request_headers.is_empty()
                || !decision.remove_request_headers.is_empty()
                || !decision.add_response_headers.is_empty()
            {
                return Err("a respond decision carries only its response".to_owned());
            }
            let response = decision
                .response
                .ok_or_else(|| "a respond decision has no response".to_owned())?;
            let status = u16::try_from(response.status)
                .ok()
                .filter(|status| (200..=599).contains(status))
                .ok_or_else(|| format!("the status {} is not 200 to 599", response.status))?;
            applied.respond = Some(Reply {
                status,
                headers: response
                    .headers
                    .iter()
                    .map(pair)
                    .collect::<Result<_, _>>()?,
                body: Bytes::from(response.body),
            });
        }
        Action::Continue => {
            if decision.response.is_some() {
                return Err("a continue decision carries no response".to_owned());
            }
            if !request_phase
                && (!decision.set_request_headers.is_empty()
                    || !decision.remove_request_headers.is_empty())
            {
                return Err(
                    "the request is already on its way: only a request phase can change it"
                        .to_owned(),
                );
            }
            for name in &decision.remove_request_headers {
                applied.remove.push(editable(name)?);
            }
            for header in &decision.set_request_headers {
                applied.set.push(pair(header)?);
            }
            for header in &decision.add_response_headers {
                applied.add_response.push(pair(header)?);
            }
        }
    }
    Ok(applied)
}

/// Why a call produced no decision.
#[derive(Debug)]
enum Refusal {
    /// The plugin is starting, down, or its circuit is open: the call was not made.
    Unavailable,
    /// No room among the calls in flight.
    Busy,
    /// The tenant's buffer budget cannot take the call.
    OverBudget,
    /// The call was made and failed, or the call was not sendable.
    Failed,
}

/// The right to make one call, held from the first check to the answer.
struct Ticket<'a> {
    entry: &'a Entry,
    permit: Permit<'a>,
    _slot: Slot<'a>,
    _charge: BufferGuard,
    tenant: Arc<TenantBudget>,
    timeout: Duration,
}

impl Ticket<'_> {
    /// Sends `call` and checks the answer for `phase`.
    async fn run(self, call: Call, phase: Phase) -> Result<Applied, Refusal> {
        let framed = match frame(&call) {
            Ok(framed) => framed,
            Err(_) => {
                self.permit.forget();
                self.entry.count(Outcome::CallTooLarge);
                return Err(Refusal::Failed);
            }
        };
        drop(call);
        let result = self
            .entry
            .client
            .process(framed, self.timeout, Some(&self.tenant))
            .await
            .and_then(|Answered { decision, charge }| {
                validate(decision, phase)
                    .map(|mut applied| {
                        if !applied.add_response.is_empty() {
                            applied.charge = charge;
                        }
                        applied
                    })
                    .map_err(CallError::Invalid)
            });
        let entry = self.entry;
        match &result {
            Ok(_) => {
                entry.count(Outcome::Ok);
                if self.permit.settle(true) == Change::Closed {
                    tracing::info!(plugin = %entry.name, "plugin circuit closed");
                }
            }
            Err(err) if err.is_plugin_failure() => {
                tracing::debug!(plugin = %entry.name, %err, "plugin call failed");
                entry.count(match err {
                    CallError::Timeout => Outcome::Timeout,
                    CallError::Unreachable(_) | CallError::Transport(_) => Outcome::Transport,
                    _ => Outcome::Invalid,
                });
                if self.permit.settle(false) == Change::Opened {
                    tracing::warn!(plugin = %entry.name, %err, "plugin circuit opened: calls stop for a while");
                }
            }
            Err(_) => self.permit.forget(),
        }
        result.map_err(|err| match err {
            CallError::OverBudget => {
                entry.count(Outcome::OverBudget);
                Refusal::OverBudget
            }
            _ => Refusal::Failed,
        })
    }
}

/// Where a call comes from.
struct Site<'a> {
    tenant: &'a str,
    app: &'a str,
    router: &'a str,
    budget: Option<&'a Arc<TenantBudget>>,
    forwarded: &'a ForwardedView,
}

fn host_of<'a>(request: &'a RequestHeader, forwarded: &'a ForwardedView) -> &'a str {
    forwarded
        .host
        .as_deref()
        .or_else(|| request.uri.authority().map(http::uri::Authority::as_str))
        .or_else(|| {
            request
                .headers
                .get(HOST)
                .and_then(|value| value.to_str().ok())
        })
        .unwrap_or_default()
}

impl Parts {
    /// Whether the request header `name` is sent to the plugin.
    fn sends_request(&self, name: &HeaderName) -> bool {
        *name != HOST
            && match &self.request_headers {
                Some(list) => list.contains(name),
                None => ![AUTHORIZATION, PROXY_AUTHORIZATION, COOKIE].contains(name),
            }
    }

    /// Whether the response header `name` is sent to the plugin.
    fn sends_response(&self, name: &HeaderName) -> bool {
        match &self.response_headers {
            Some(list) => list.contains(name),
            None => *name != SET_COOKIE,
        }
    }

    fn selected<'a>(&self, request: &'a RequestHeader) -> Vec<(&'a HeaderName, &'a HeaderValue)> {
        request
            .headers
            .iter()
            .filter(|(name, _)| self.sends_request(name))
            .collect()
    }

    /// What a call of this request weighs, before any of it is copied.
    fn weigh(
        &self,
        request: &RequestHeader,
        selected: &[(&HeaderName, &HeaderValue)],
        response: Option<(&ResponseHeader, &[(&HeaderName, &HeaderValue)])>,
        body: usize,
        host: &str,
    ) -> usize {
        let headers = |list: &[(&HeaderName, &HeaderValue)]| -> usize {
            list.iter()
                .map(|(name, value)| name.as_str().len() + value.len() + HEADER_OVERHEAD)
                .sum()
        };
        let target = request
            .uri
            .path_and_query()
            .map_or(1, |target| target.as_str().len());
        let response = response.map_or(0, |(_, list)| headers(list));
        CALL_OVERHEAD
            + self.config.len()
            + target
            + host.len()
            + headers(selected)
            + response
            + body
    }

    fn headers_of(list: &[(&HeaderName, &HeaderValue)]) -> Vec<Header> {
        list.iter()
            .map(|(name, value)| Header {
                name: name.as_str().to_owned(),
                value: value.as_bytes().to_vec(),
            })
            .collect()
    }

    /// Takes everything a call needs but its bytes: the plugin is up, its circuit lets a call
    /// through, a place among its calls in flight is free, and the tenant has paid for `weight`
    /// bytes, twice (the message and its encoding exist together).
    fn begin(&self, site: &Site<'_>, weight: usize) -> Result<Ticket<'_>, Refusal> {
        let Some(bound) = &self.bound else {
            return Err(Refusal::Unavailable);
        };
        let entry = &*bound.entry;
        if !entry.is_ready() {
            entry.count(Outcome::Unavailable);
            return Err(Refusal::Unavailable);
        }
        let Some(permit) = entry.circuit.admit() else {
            entry.count(Outcome::Unavailable);
            return Err(Refusal::Unavailable);
        };
        let slot = match entry.slots.acquire(site.tenant, bound.share) {
            Ok(slot) => slot,
            Err(why) => {
                permit.forget();
                return Err(match why {
                    Busy::Plugin | Busy::Tenant => {
                        entry.count(Outcome::Busy);
                        Refusal::Busy
                    }
                    Busy::Unlisted => {
                        entry.count(Outcome::Unavailable);
                        Refusal::Unavailable
                    }
                });
            }
        };
        // No budget for the tenant means nothing to charge the call to: refused.
        let charged = site.budget.and_then(|budget| {
            let bytes =
                u64::try_from(weight.saturating_mul(2).saturating_add(8)).unwrap_or(u64::MAX);
            budget
                .charge(bytes)
                .map(|guard| (guard, Arc::clone(budget)))
        });
        let Some((charge, tenant)) = charged else {
            permit.forget();
            entry.count(Outcome::OverBudget);
            return Err(Refusal::OverBudget);
        };
        Ok(Ticket {
            entry,
            permit,
            _slot: slot,
            _charge: charge,
            tenant,
            timeout: self.timeout,
        })
    }

    #[allow(
        clippy::too_many_arguments,
        reason = "the fields of one message, set in one place"
    )]
    fn call(
        &self,
        site: &Site<'_>,
        phase: Phase,
        request: &RequestHeader,
        selected: &[(&HeaderName, &HeaderValue)],
        response: Option<(&ResponseHeader, &[(&HeaderName, &HeaderValue)])>,
        body: &Bytes,
        host: &str,
    ) -> Call {
        Call {
            phase: phase as i32,
            tenant: site.tenant.to_owned(),
            app: site.app.to_owned(),
            router: site.router.to_owned(),
            middleware: self.name.to_string(),
            config: self.config.to_vec(),
            client_addr: if site.forwarded.client_ip == UNKNOWN {
                String::new()
            } else {
                site.forwarded.client_ip.to_string()
            },
            method: request.method.as_str().to_owned(),
            target: request
                .uri
                .path_and_query()
                .map_or("/", |target| target.as_str())
                .to_owned(),
            host: host.to_owned(),
            scheme: site.forwarded.proto.as_str().to_owned(),
            headers: Self::headers_of(selected),
            body: body.to_vec(),
            status: response.map_or(0, |(head, _)| u32::from(head.status.as_u16())),
            response_headers: response.map_or_else(Vec::new, |(_, list)| Self::headers_of(list)),
        }
    }

    /// The ticket and the call of a request phase, built in one sync step.
    fn prepare_request(
        &self,
        cx: &RequestCx<'_>,
        phase: Phase,
        body: &Bytes,
    ) -> Result<(Ticket<'_>, Call), Refusal> {
        let site = Site {
            tenant: cx.app.tenant(),
            app: cx.app.id(),
            router: cx.router,
            budget: cx.tenant,
            forwarded: cx.forwarded,
        };
        let request = cx.session.req_header();
        let selected = self.selected(request);
        let host = host_of(request, cx.forwarded);
        let weight = self.weigh(request, &selected, None, body.len(), host);
        let ticket = self.begin(&site, weight)?;
        let call = self.call(&site, phase, request, &selected, None, body, host);
        Ok((ticket, call))
    }

    /// The ticket and the call of the response phase.
    fn prepare_response(&self, cx: &ResponsePhase<'_>) -> Result<(Ticket<'_>, Call), Refusal> {
        let site = Site {
            tenant: cx.app.tenant(),
            app: cx.app.id(),
            router: cx.router,
            budget: cx.tenant,
            forwarded: cx.forwarded,
        };
        let selected = self.selected(cx.request);
        let sent: Vec<(&HeaderName, &HeaderValue)> = cx
            .response
            .headers
            .iter()
            .filter(|(name, _)| self.sends_response(name))
            .collect();
        let host = host_of(cx.request, cx.forwarded);
        let response = Some((&*cx.response, sent.as_slice()));
        let weight = self.weigh(cx.request, &selected, response, 0, host);
        let ticket = self.begin(&site, weight)?;
        let call = self.call(
            &site,
            Phase::ResponseHeaders,
            cx.request,
            &selected,
            response,
            &Bytes::new(),
            host,
        );
        Ok((ticket, call))
    }

    /// What a refusal means for the request: the error that answers it, or `None` to let it go
    /// on. A tenant over its budget is refused either way: its own memory is what ran out.
    fn verdict(&self, refusal: &Refusal, capacity: &mut bool) -> Option<AppError> {
        match refusal {
            Refusal::OverBudget => {
                *capacity = true;
                Some(AppError::PluginSaturated)
            }
            other => match self.on_error {
                OnPluginError::FailOpen => {
                    if let Some(bound) = &self.bound {
                        bound.entry.count(Outcome::FailedOpen);
                    }
                    None
                }
                OnPluginError::FailClosed => {
                    if matches!(other, Refusal::Busy) {
                        *capacity = true;
                        Some(AppError::PluginSaturated)
                    } else {
                        Some(AppError::PluginUnavailable)
                    }
                }
            },
        }
    }

    /// Reads the request body, at most `max` bytes, so the call and the upstream both have it.
    /// The inner `Err` is the refusal to write.
    async fn hold_body(
        &self,
        cx: &mut RequestCx<'_>,
        state: &mut State,
        max: usize,
    ) -> pingora::Result<Result<Bytes, AppError>> {
        let session = &mut *cx.session;
        if session.is_upgrade_req()
            || session.req_header().method == Method::CONNECT
            || session.is_body_empty()
        {
            return Ok(Ok(Bytes::new()));
        }
        let max64 = u64::try_from(max).unwrap_or(u64::MAX);
        let expects = session.req_header().version == http::Version::HTTP_11
            && session
                .req_header()
                .headers
                .get(http::header::EXPECT)
                .is_some_and(|value| value.as_bytes().eq_ignore_ascii_case(b"100-continue"));
        let declared = session
            .req_header()
            .headers
            .get(http::header::CONTENT_LENGTH)
            .and_then(|value| value.to_str().ok())
            .and_then(|text| text.trim().parse::<u64>().ok());
        if declared.is_some_and(|declared| declared > max64) {
            return Ok(Err(if expects {
                AppError::ExpectationFailed
            } else {
                AppError::PayloadTooLarge
            }));
        }
        // The replay buffer and the call's copy of the body: charged before the first byte.
        let Some(tenant) = cx.tenant else {
            return Ok(Err(AppError::PluginSaturated));
        };
        let Some(guard) = tenant.charge(declared.unwrap_or(max64)) else {
            *cx.capacity_refusal = true;
            return Ok(Err(AppError::PluginSaturated));
        };
        state.held.push(guard);
        buffering::hold_body(session, cx.body_held, max64).await
    }

    /// Applies the request-changing part of a decision to the request.
    fn apply(
        applied: Applied,
        request: &mut RequestHeader,
        state: &mut State,
    ) -> pingora::Result<Option<Reply>> {
        for name in &applied.remove {
            request.remove_header(name);
        }
        for (name, value) in applied.set {
            request.insert_header(name, value)?;
        }
        if !applied.add_response.is_empty() {
            state.response_headers.extend(applied.add_response);
            state.held.extend(applied.charge);
        }
        Ok(applied.respond)
    }

    /// Writes a plugin's answer to the client.
    async fn answer(cx: &mut RequestCx<'_>, reply: Reply) -> pingora::Result<()> {
        let bodyless =
            matches!(reply.status, 204 | 304) || cx.session.req_header().method == Method::HEAD;
        let mut head = ResponseHeader::build(reply.status, Some(reply.headers.len() + 1))?;
        for (name, value) in reply.headers {
            head.append_header(name, value)?;
        }
        if !matches!(reply.status, 204 | 304) {
            head.insert_header("content-length", reply.body.len().to_string())?;
        }
        cx.session
            .write_response_header(Box::new(head), bodyless)
            .await?;
        if bodyless {
            return Ok(());
        }
        cx.session.write_response_body(Some(reply.body), true).await
    }
}

impl Plugin {
    /// Resolves the plugin this middleware names against the operator's `plugins` and takes the
    /// tenant's share of its calls.
    fn bind(&mut self, app: &App, snapshot: &Snapshot, plugins: &Plugins) -> Result<(), Invalid> {
        let parts = &mut *self.0;
        let entry = plugins.get(&parts.plugin).ok_or_else(|| {
            Invalid::new(
                "unknown_plugin",
                format!(
                    "plugin {:?} is not declared in the operator's PLUGINS_FILE",
                    parts.plugin
                ),
            )
            .with("plugin", &*parts.plugin)
        })?;
        if !entry.allows(&app.tenant) {
            return Err(Invalid::new(
                "plugin_forbidden",
                format!(
                    "plugin {:?} is not available to tenant {}; its tenants are listed in the operator's PLUGINS_FILE",
                    parts.plugin, app.tenant
                ),
            )
            .with("plugin", &*parts.plugin)
            .with("tenant", &*app.tenant));
        }
        for (wanted, phase, name) in [
            (
                parts.phases.request_headers,
                Phase::RequestHeaders,
                "request_headers",
            ),
            (
                parts.phases.request_body,
                Phase::RequestBody,
                "request_body",
            ),
            (
                parts.phases.response,
                Phase::ResponseHeaders,
                "response_headers",
            ),
        ] {
            if wanted && !entry.serves(phase) {
                return Err(invalid(format!(
                    "plugin {:?} does not serve the phase {name}",
                    parts.plugin
                )));
            }
        }
        if parts.timeout > plugins.max_timeout() {
            return Err(invalid(format!(
                "`timeout_ms` {} is over REQUEST_TIMEOUT_SECS ({} ms)",
                parts.timeout.as_millis(),
                plugins.max_timeout().as_millis()
            )));
        }
        let budget = snapshot
            .tenants
            .iter()
            .find(|tenant| tenant.id == app.tenant)
            .map_or(u64::MAX, |tenant| tenant.budget.max_buffer_bytes);
        let needed = 2 * (parts.config.len() + parts.body_max.unwrap_or(0) + 8 * 1024);
        if budget < u64::try_from(needed).unwrap_or(u64::MAX) {
            return Err(invalid(format!(
                "tenant {} has max_buffer_bytes {budget}, below the {needed} bytes one call reserves; raise the budget or shrink `config` or `body.max_bytes`",
                app.tenant
            )));
        }
        let weight_of = |id: &str| {
            snapshot
                .tenants
                .iter()
                .find(|tenant| &*tenant.id == id)
                .map_or(0, |tenant| u64::from(tenant.weight))
        };
        let sum: u64 = entry.spec.tenants.iter().map(|id| weight_of(id)).sum();
        parts.bound = Some(Bound {
            entry: Arc::clone(entry),
            share: Slots::share(entry.spec.max_concurrent, weight_of(&app.tenant), sum),
        });
        Ok(())
    }

    /// Whether the middleware asks the plugin at the response phase.
    fn has_response_phase(&self) -> bool {
        self.0.phases.response
    }

    /// The response-phase hook: asks the plugin about the upstream's response head and adds
    /// the headers it answers with.
    async fn response_phase(&self, cx: &mut ResponsePhase<'_>) -> Result<(), AppError> {
        let parts = &*self.0;
        let result = match parts.prepare_response(cx) {
            Ok((ticket, call)) => ticket.run(call, Phase::ResponseHeaders).await,
            Err(refusal) => Err(refusal),
        };
        match result {
            Ok(applied) => {
                for (name, value) in applied.add_response {
                    cx.response
                        .append_header(name, value)
                        .map_err(|_| AppError::PluginUnavailable)?;
                }
                Ok(())
            }
            Err(refusal) => {
                let mut capacity = false;
                parts.verdict(&refusal, &mut capacity).map_or(Ok(()), Err)
            }
        }
    }
}

/// Binds every `plugin` middleware of the snapshot (`stages` are the compiled stages of each
/// app, in the snapshot's order): the plugin it names must exist, list the app's tenant and
/// serve the phases it asks for.
pub(crate) fn bind<'a>(
    snapshot: &Snapshot,
    plugins: &Plugins,
    stages: impl Iterator<Item = &'a mut [Named]>,
) -> Vec<Rejected> {
    let mut rejected = Vec::new();
    for (app, stages) in snapshot.apps.iter().zip(stages) {
        for named in stages {
            if let Stage::Plugin(plugin) = &mut named.stage
                && let Err(invalid) = plugin.bind(app, snapshot, plugins)
            {
                rejected.push(Rejected::new(
                    app,
                    format!("middleware {}", named.name),
                    invalid,
                ));
            }
        }
    }
    rejected
}

/// Runs the response-phase hooks of the plugin stages of `chain`, last stage first.
///
/// # Errors
///
/// The [`AppError`] that replaces the response: a failed call of a `fail_closed` stage, or a
/// tenant over its budget.
pub async fn run_response(
    stages: &[Named],
    chain: &[usize],
    cx: &mut ResponsePhase<'_>,
    state: &mut super::State,
) -> Result<(), AppError> {
    for (position, index) in chain.iter().enumerate().rev() {
        if let (
            Some(Named {
                stage: Stage::Plugin(plugin),
                ..
            }),
            Some(StageState::Plugin(_)),
        ) = (stages.get(*index), state.stages.get_mut(position))
            && plugin.has_response_phase()
        {
            plugin.response_phase(cx).await?;
        }
    }
    Ok(())
}

impl Kind for Plugin {
    type State = State;

    fn compile(declared: &Declared, _cx: &mut CompileCx<'_>) -> Result<Self, Invalid> {
        let config: Config =
            serde_json::from_value(Value::Object(declared.config.clone())).map_err(invalid)?;
        if !registry::valid_name(&config.plugin) {
            return Err(invalid(format!(
                "`plugin` {:?} is not the name of a plugin",
                config.plugin
            )));
        }
        let given = match &config.config {
            None | Some(Value::Null) => Bytes::new(),
            Some(value) => Bytes::from(serde_json::to_vec(value).map_err(invalid)?),
        };
        if given.len() > CONFIG_MAX {
            return Err(invalid(format!(
                "`config` is {} bytes of JSON, over the {CONFIG_MAX} a plugin is given",
                given.len()
            )));
        }
        let mut phases = Phases::default();
        match &config.phases {
            None => phases.request_headers = true,
            Some(list) if list.is_empty() => {
                return Err(invalid(
                    "`phases` is empty; leave it out for request_headers",
                ));
            }
            Some(list) => {
                for phase in list {
                    match phase {
                        PhaseName::RequestHeaders => phases.request_headers = true,
                        PhaseName::RequestBody => phases.request_body = true,
                        PhaseName::ResponseHeaders => phases.response = true,
                    }
                }
            }
        }
        let body_max = match (phases.request_body, config.body) {
            (true, Some(body)) if (1..=MAX_BODY).contains(&body.max_bytes) => Some(body.max_bytes),
            (true, Some(_)) => {
                return Err(invalid(format!("`body.max_bytes` is in 1..={MAX_BODY}")));
            }
            (true, None) => {
                return Err(invalid(
                    "the `request_body` phase needs `body: {\"max_bytes\": ...}`",
                ));
            }
            (false, Some(_)) => {
                return Err(invalid(
                    "`body` is for the `request_body` phase, which is not in `phases`",
                ));
            }
            (false, None) => None,
        };
        let timeout_ms = config.timeout_ms.unwrap_or(DEFAULT_TIMEOUT_MS);
        if !(1..=MAX_TIMEOUT_MS).contains(&timeout_ms) {
            return Err(invalid(format!("`timeout_ms` is in 1..={MAX_TIMEOUT_MS}")));
        }
        let listed = |list: &Option<Vec<String>>, field: &str| {
            list.as_deref().map(|list| names(list, field)).transpose()
        };
        Ok(Self(Box::new(Parts {
            name: declared.name.clone(),
            plugin: config.plugin.into(),
            config: given,
            phases,
            on_error: config.on_plugin_error.unwrap_or_default(),
            timeout: Duration::from_millis(u64::from(timeout_ms)),
            request_headers: listed(&config.request_headers, "request_headers")?,
            response_headers: listed(&config.response_headers, "response_headers")?,
            body_max,
            bound: None,
        })))
    }

    async fn request(&self, cx: &mut RequestCx<'_>, state: &mut State) -> pingora::Result<Flow> {
        let parts = &*self.0;
        for phase in [Phase::RequestHeaders, Phase::RequestBody] {
            if !parts.phases.has(phase) {
                continue;
            }
            let body = match (phase, parts.body_max) {
                (Phase::RequestBody, Some(max)) => match parts.hold_body(cx, state, max).await? {
                    Ok(body) => body,
                    Err(refusal) => {
                        *cx.capacity_refusal |= refusal.is_capacity_refusal();
                        respond::write_error(cx.session, &refusal).await?;
                        return Ok(Flow::Respond);
                    }
                },
                _ => Bytes::new(),
            };
            let result = match parts.prepare_request(cx, phase, &body) {
                Ok((ticket, call)) => {
                    drop(body);
                    ticket.run(call, phase).await
                }
                Err(refusal) => Err(refusal),
            };
            match result {
                Ok(applied) => {
                    if let Some(reply) = Parts::apply(applied, cx.session.req_header_mut(), state)?
                    {
                        Parts::answer(cx, reply).await?;
                        return Ok(Flow::Respond);
                    }
                }
                Err(refusal) => {
                    let mut capacity = false;
                    let answer = parts.verdict(&refusal, &mut capacity);
                    *cx.capacity_refusal |= capacity;
                    if let Some(err) = answer {
                        respond::write_error(cx.session, &err).await?;
                        return Ok(Flow::Respond);
                    }
                }
            }
        }
        Ok(Flow::Continue)
    }

    fn response(&self, response: &mut ResponseHeader, state: &mut State) -> pingora::Result<()> {
        for (name, value) in std::mem::take(&mut state.response_headers) {
            response.append_header(name, value)?;
        }
        Ok(())
    }

    /// Dropping the middleware, asking another plugin, asking at fewer phases, and letting a
    /// failed call through all take away what the plugin guarded.
    fn posture(&self, new: Option<&Self>) -> Vec<&'static str> {
        let Some(new) = new else {
            return vec![kind::REMOVED];
        };
        let mut kinds = Vec::new();
        if self.0.plugin != new.0.plugin {
            kinds.push(kind::CHANGED);
        }
        if self.0.on_error == OnPluginError::FailClosed && new.0.on_error == OnPluginError::FailOpen
        {
            kinds.push(kind::FAIL_OPEN);
        }
        if !self.0.phases.within(new.0.phases) {
            kinds.push(kind::PHASES_REMOVED);
        }
        kinds
    }

    /// The configuration without the `config` the plugin is given: that is the tenant's own and
    /// may hold a secret.
    fn describe(&self) -> Value {
        let parts = &*self.0;
        fn list(names: Option<&[HeaderName]>) -> Option<Vec<&str>> {
            names.map(|names| names.iter().map(HeaderName::as_str).collect())
        }
        json!({
            "plugin": &*parts.plugin,
            "phases": parts.phases.names(),
            "on_plugin_error": match parts.on_error {
                OnPluginError::FailClosed => "fail_closed",
                OnPluginError::FailOpen => "fail_open",
            },
            "timeout_ms": u64::try_from(parts.timeout.as_millis()).unwrap_or(u64::MAX),
            "request_headers": list(parts.request_headers.as_deref()),
            "response_headers": list(parts.response_headers.as_deref()),
            "body_max_bytes": parts.body_max,
            "config_bytes": parts.config.len(),
        })
    }
}

