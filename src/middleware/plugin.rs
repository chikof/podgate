/// Bytes a call is charged for besides its parts: the fixed fields.
const CALL_OVERHEAD: usize = 1024;

/// Bytes per header of a call: the lengths of the two prefixes.
const HEADER_OVERHEAD: usize = 16;

/// The most names in `request_headers` and `response_headers`.
const MAX_NAMES: usize = 64;

/// The largest `body.max_bytes`.
const MAX_BODY: usize = 1 << 20;

